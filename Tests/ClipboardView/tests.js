(async () => {
  const results = [];
  // All fixture APIs are in-memory Promises. Drain their microtasks deterministically;
  // hidden WKWebView timers may be heavily throttled and are not part of these tests.
  const wait = async () => { for (let i = 0; i < 40; i++) await Promise.resolve(); };
  const assert = (condition, name) => { if (!condition) throw Error(name); results.push('PASS: ' + name); window.webkit?.messageHandlers?.testResult?.postMessage({ progress: name }); };
  const key = (target, value, options = {}) => target.dispatchEvent(new KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true, ...options }));
  try {
    for (let i = 0; i < 100 && (!ready || items.length !== 6); i++) await wait();
    assert(ready && items.length === 6 && viewMode === 'cards', 'default cards view loads six synthetic entries');
    assert(fakeGetCalls === 0, 'cards do not eagerly fetch full clipboard contents');
    assert(listEl.scrollWidth > listEl.clientWidth, 'cards form a horizontally scrolling strip');
    assert(document.body.scrollWidth <= innerWidth, 'layout does not overflow window horizontally');
    const first = listEl.querySelector('[data-id]');
    assert(first.getBoundingClientRect().height > 72, 'cards retain useful preview height');
    assert(document.querySelector('footer').getBoundingClientRect().bottom <= innerHeight + 1, 'action footer remains inside the window');
    assert($('paste').getBoundingClientRect().right <= innerWidth, 'paste button remains visible at narrow widths');
    assert(first.getAttribute('aria-selected') === 'true' && listEl.getAttribute('aria-activedescendant') === first.id, 'keyboard selection exposed to assistive technology');
    assert(!window.__injected && !listEl.querySelector('[data-id="unsafe"] img'), 'copied HTML displayed as literal text');
    key(searchEl, 'ArrowRight');
    assert(selectedId === 'url', 'right arrow selects next card from empty search');
    searchEl.value = 'abc'; key(searchEl, 'ArrowLeft');
    assert(selectedId === 'url', 'search editing retains left and right arrow behavior');
    searchEl.value = '';
    listEl.focus(); key(listEl, ' '); await wait();
    assert(previewOpen && preview.textContent.includes('github.com'), 'space opens full preview');
    $('close-preview').click();
    assert(!previewOpen, 'close preview returns to cards');
    document.querySelector('[data-filter="image"]').click(); await wait();
    assert(items.length === 1 && items[0].id === 'pic', 'image filter');
    await fillThumbnail(listEl.querySelector('[data-image-id]'));
    assert(!!listEl.querySelector('.thumbnail img') && fakeCalls.some((c) => c[0] === 'thumbnail' && c[2] === 768), 'card thumbnail requests a Retina-ready 768px image');
    const imageCard = listEl.querySelector('[data-id="pic"]');
    const imageArea = imageCard.querySelector('.thumbnail').getBoundingClientRect();
    assert(imageCard.getBoundingClientRect().width >= Math.min(384, innerWidth - 44) - 1, 'image cards use a larger responsive width');
    assert(imageArea.width > imageCard.clientWidth - 12, 'image preview fills card width with minimal padding');
    if (innerHeight >= 440 && innerWidth >= 850) assert(imageArea.height >= 200, 'tall shelf gives images at least 200px of preview height');
    assert(getComputedStyle(imageCard.querySelector('.thumbnail img')).objectFit === 'contain', 'image aspect ratio preserved without cropping');
    const actionButtons = imageCard.querySelectorAll('.card-action');
    assert(actionButtons.length === 2, 'image card has separate send and copy buttons');
    const cardRect = imageCard.getBoundingClientRect();
    for (const button of actionButtons) {
      const rect = button.getBoundingClientRect();
      assert(rect.height >= 30 && rect.right <= cardRect.right && rect.bottom <= cardRect.bottom,
        'card action is visible inside the bottom-right area');
      assert(!!button.title && !!button.getAttribute('aria-label'), 'card action has accessible label and tooltip');
    }
    document.querySelector('[data-filter="all"]').click();
    assert([...listEl.querySelectorAll('[data-id]')].every((card) => card.querySelectorAll('.card-action').length === 2), 'every card type includes both actions');
    select('note');
    const beforeCardCopy = fakeCalls.length;
    listEl.querySelector('[data-id="pic"] .card-copy').click(); await wait();
    const cardCopyCalls = fakeCalls.slice(beforeCardCopy);
    assert(cardCopyCalls.filter((c) => c[0] === 'copy').length === 1 && cardCopyCalls.some((c) => c[0] === 'copy' && c[1] === 'pic'), 'copy targets clicked image instead of selected text');
    assert(!cardCopyCalls.some((c) => c[0] === 'paste' || c[0] === 'hide') && $('toast').textContent === t('copied'), 'card copy shows feedback and stays open without sending');
    for (const id of ['url', 'pic', 'files']) {
      select('note');
      const beforeSend = fakeCalls.length;
      listEl.querySelector(`[data-id="${id}"] .card-paste`).click(); await wait();
      const sends = fakeCalls.slice(beforeSend).filter((c) => c[0] === 'paste');
      assert(sends.length === 1 && sends[0][1] === id, 'send targets clicked ' + id + ' card exactly once');
    }
    const copyButton = listEl.querySelector('[data-id="files"] .card-copy');
    const beforeDouble = fakeCalls.length;
    copyButton.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 })); await wait();
    copyButton.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 2 }));
    copyButton.dispatchEvent(new MouseEvent('dblclick', { bubbles: true, detail: 2 })); await wait();
    assert(fakeCalls.slice(beforeDouble).filter((c) => c[0] === 'copy').length === 1 && !fakeCalls.slice(beforeDouble).some((c) => c[0] === 'paste'), 'double-clicking copy never repeats or bubbles into card send');
    const beforeKey = fakeCalls.length;
    key(copyButton, 'Enter'); key(copyButton, ' '); await wait();
    assert(fakeCalls.length === beforeKey && !previewOpen, 'button keyboard events do not trigger global paste or preview');
    fakeCopyOK = false;
    copyButton.click(); await wait();
    assert($('toast').textContent === t('actionError'), 'failed card copy shows an error');
    fakeCopyOK = true; fakePasteOK = false;
    listEl.querySelector('[data-id="pic"] .card-paste').click(); await wait();
    assert($('toast').textContent === t('needAccess'), 'send without Accessibility permission gives copy fallback guidance');
    fakePasteOK = true;
    let finishCopy;
    fakeCopyHook = () => new Promise((resolve) => { finishCopy = resolve; });
    const beforePending = fakeCalls.length;
    copyButton.click(); copyButton.click();
    assert(fakeCalls.slice(beforePending).filter((c) => c[0] === 'copy').length === 1, 'pending card action blocks duplicate requests');
    finishCopy(true); await wait(); fakeCopyHook = null;
    document.querySelector('[data-filter="link"]').click();
    assert(items.length === 1 && items[0].id === 'url', 'link filter');
    document.querySelector('[data-filter="text"]').click();
    assert(items.length === 3 && items.every((i) => kindOf(i) === 'text'), 'text filter excludes links');
    document.querySelector('[data-filter="files"]').click();
    assert(items.length === 1 && listEl.textContent.includes('设计方案.pdf'), 'files show filenames');
    document.querySelector('[data-filter="pinned"]').click();
    assert(items.length === 1 && items[0].pinned, 'pinned filter');
    document.querySelector('[data-filter="all"]').click();
    await setView('list'); await wait();
    assert(document.body.dataset.view === 'list' && fakeStorage.viewMode === 'list', 'view mode switch persists');
    assert(getComputedStyle($('detail')).display !== 'none' && preview.textContent.includes('完整预览'), 'list retains full detail panel');
    assert(getComputedStyle(listEl).overflowY === 'auto', 'list supports vertical scrolling');
    assert(getComputedStyle(listEl.querySelector('.card-stats')).display === 'none', 'compact list hides card actions and retains toolbar controls');
    fakeSavedError = true;
    await setView('cards');
    assert(viewMode === 'cards' && fakeCalls.at(-1)[0] === 'view' && $('toast').textContent === t('saveError'), 'failed preference save does not prevent layout change');
    fakeSavedError = false;
    await setView('cards');
    document.querySelector('[data-filter="all"]').click();
    select('url'); await togglePin();
    assert(selected().pinned, 'pin action retains selection');
    select('code'); await remove();
    assert(!items.some((i) => i.id === 'code') && selectedId != null, 'delete selects neighboring item');
    key(searchEl, '2', { metaKey: true }); await wait();
    assert(fakeCalls.some((c) => c[0] === 'paste' && c[1] === items[1].id), 'command-number pastes the matching visible entry');
    key(searchEl, 'Enter', { metaKey: true }); await wait();
    assert(fakeCalls.some((c) => c[0] === 'copy') && fakeCalls.some((c) => c[0] === 'hide'), 'command-enter copies and hides');
    const beforeButton = fakeCalls.filter((c) => c[0] === 'paste').length;
    key($('view-list'), 'Enter'); await wait();
    assert(fakeCalls.filter((c) => c[0] === 'paste').length === beforeButton, 'enter on toolbar button never triggers paste');
    // Out-of-order search results must not overwrite the newest query.
    const pending = [];
    fakeListHook = () => new Promise((resolve) => pending.push(resolve));
    const older = load(), newer = load();
    pending[1]([fixtures[1]]); await newer;
    pending[0]([fixtures[0]]); await older;
    assert(items.length === 1 && items[0].id === 'url', 'stale search responses ignored');
    fakeListHook = null; await load();
    let detailResolve;
    fakeGetHook = () => new Promise((resolve) => { detailResolve = resolve; });
    togglePreview(true);
    sourceItems = []; applyFilter();
    detailResolve(fixtures[0]); await wait();
    assert(document.body.classList.contains('no-item') && !preview.textContent && $('paste').disabled, 'late detail result cannot revive an empty selection');
    fakeGetHook = null; togglePreview(false); await load();
    $('clear').click();
    assert(fakeItems.length > 0 && $('clear').textContent === t('clearConfirm'), 'first clear click only arms confirmation');
    $('clear').click(); await wait(80);
    assert(fakeItems.length === 2 && fakeItems.every((i) => i.pinned), 'confirmed clear preserves pinned records');
    searchEl.value = 'no-matching-fixture'; await load();
    assert(items.length === 0 && listEl.textContent.includes(t('noResults')) && $('paste').disabled, 'empty search state disables actions');
    searchEl.value = '';
    fakeItems = Array.from({ length: 1000 }, (_, index) => ({ ...fixtures[0], id: 'bulk-' + index, pinned: false }));
    const start = performance.now(); await load();
    assert(items.length === 1000 && listEl.querySelectorAll('[data-id]').length === 1000, 'full thousand-entry history remains available');
    results.push(`INFO: 1000-card render ${(performance.now() - start).toFixed(0)}ms`);
    fakeItems = fixtures.map((i) => ({ ...i })); fakeStorage.viewMode = 'list';
    await window.fixtureEnter();
    assert(viewMode === 'list', 'reopening restores saved list view');
    await setView('cards');
    if (window.webkit?.messageHandlers?.testResult) window.webkit.messageHandlers.testResult.postMessage({ ok: true, results });
    else { window.testResults = results; document.title = 'PASS — Clipboard view tests'; }
  } catch (error) {
    if (window.webkit?.messageHandlers?.testResult) window.webkit.messageHandlers.testResult.postMessage({ ok: false, results, error: error.stack || String(error) });
    else { window.testResults = [...results, 'FAIL: ' + error.stack]; document.title = 'FAIL — Clipboard view tests'; }
  }
})();
